# Convertir a EE
def gdf_to_ee_simple(gdf):
    features = []
    for _, row in gdf.iterrows():
        geojson = row['geometry'].__geo_interface__
        if geojson['type'] == 'Polygon':
            geom = ee.Geometry.Polygon(geojson['coordinates'])
        elif geojson['type'] == 'MultiPolygon':
            geom = ee.Geometry.MultiPolygon(geojson['coordinates'])
        else:
            continue
        feat = ee.Feature(geom, {'cod_depto': row['cod_depto']})
        features.append(feat)
    return ee.FeatureCollection(features)

fc = gdf_to_ee_simple(gdf)
print(f"FeatureCollection creada con {fc.size().getInfo()} departamentos")

# Función de extracción
def extraer_media(anio, col_id):
    img = (ee.ImageCollection(col_id)
           .filter(ee.Filter.calendarRange(anio, anio, 'year'))
           .first()
           .select('average'))
    stats = img.reduceRegions(collection=fc, reducer=ee.Reducer.mean(), scale=500)
    return stats.getInfo()

