def fisher_adf(df, var, maxlag=1):
    pvals = []
    for cod in sorted(df['cod_depto'].unique()):
        serie = df[df['cod_depto'] == cod][var].dropna().values
        if len(serie) < 6:
            continue
        try:
            res = adfuller(serie, maxlag=maxlag, regression='c', autolag=None)
            pvals.append(res[1])
        except:
            continue
    if len(pvals) == 0:
        return np.nan, np.nan, 0
    stat = -2 * np.sum(np.log(pvals))
    p_comb = 1 - chi2.cdf(stat, 2 * len(pvals))
    return stat, p_comb, len(pvals)

