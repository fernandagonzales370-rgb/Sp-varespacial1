def spatial_lag_by_year(df, var, w):
    lags = []
    for year in sorted(df['anio'].unique()):
        df_y = df[df['anio'] == year].set_index('cod_depto').sort_index()
        y = df_y[var].reindex([str(i).zfill(2) for i in w.id_order]).values
        lag = lag_spatial(w, y)
        temp = pd.DataFrame({'cod_depto': [str(i).zfill(2) for i in w.id_order],
                            'anio': year, f'W_{var}': lag})
        lags.append(temp)
    return pd.concat(lags, ignore_index=True)

def preparar_con_W(df, w, nombre):
    d = df.drop(columns=[c for c in df.columns if c.startswith('W_')], errors='ignore').copy()
    wt = spatial_lag_by_year(d, 'dlog_tasa',  w)
    wl = spatial_lag_by_year(d, 'dlog_luces', w)
    d = d.merge(wt, on=['cod_depto','anio'], how='left')
    d = d.merge(wl, on=['cod_depto','anio'], how='left')
    d['W_dlog_tasa_l1']  = d.groupby('cod_depto')['W_dlog_tasa'].shift(1)
    d['W_dlog_luces_l1'] = d.groupby('cod_depto')['W_dlog_luces'].shift(1)
    d['dlog_tasa_l1']    = d.groupby('cod_depto')['dlog_tasa'].shift(1)
    d['dlog_luces_l1']   = d.groupby('cod_depto')['dlog_luces'].shift(1)
    dest = d.dropna(subset=['dlog_tasa_l1','dlog_luces_l1','W_dlog_tasa_l1','W_dlog_luces_l1']).copy()
    dest = dest.sort_values(['anio','cod_depto']).reset_index(drop=True)
    yd = pd.get_dummies(dest['anio'], prefix='y', drop_first=True).astype(float)
    dest = pd.concat([dest, yd], axis=1)
    Xv = ['dlog_tasa_l1','dlog_luces_l1','W_dlog_tasa_l1','W_dlog_luces_l1'] + list(yd.columns)
    return dest, Xv

