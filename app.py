def estimar_base_con_W(df, w, nombre_w):
    """Estima el SpVAR base (solo rezagos + year FE) con una W dada"""
    df_temp = df.drop(columns=[c for c in df.columns if c.startswith('W_')]).copy()

    # Crear rezagos espaciales con la W actual
    w_tasa  = spatial_lag_by_year(df_temp, 'dlog_tasa',  w)
    w_luces = spatial_lag_by_year(df_temp, 'dlog_luces', w)

    df_temp = df_temp.merge(w_tasa,  on=['cod_depto','anio'], how='left', suffixes=('','_drop'))
    df_temp = df_temp.merge(w_luces, on=['cod_depto','anio'], how='left', suffixes=('','_drop'))

    # Limpiar columnas duplicadas si las hay
    df_temp = df_temp.loc[:, ~df_temp.columns.str.endswith('_drop')]

    df_temp['W_dlog_tasa_l1']  = df_temp.groupby('cod_depto')['W_dlog_tasa'].shift(1)
    df_temp['W_dlog_luces_l1'] = df_temp.groupby('cod_depto')['W_dlog_luces'].shift(1)

    df_est = df_temp.dropna(subset=['dlog_tasa_l1','dlog_luces_l1',
                                    'W_dlog_tasa_l1','W_dlog_luces_l1']).copy()

    year_dummies = pd.get_dummies(df_est['anio'], prefix='y', drop_first=True)
    df_est = pd.concat([df_est, year_dummies], axis=1)

